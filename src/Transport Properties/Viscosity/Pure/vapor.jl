function viscosity(model::CEB_Visc, T::Number)    # Динамическая вязкость чистых газов
    σ₀ = model.params[1]    # Диаметр столкновения [м]
    ε = model.params[2]    # Глубина потенциальной ямы (ε/kB) [К]
    μ = model.params[3]    # Дипольный момент молекулы [Д]
    M = model.params[4]    # Молярная масса молекулы [кг/моль]

    kB = 1.380649 * 10.0^-23    # Постоянная Больцмана [Дж/К]
    Nₐ = 6.02214076 * 10.0^23    # Число Авогадро [моль⁻¹]
    ε₀ = 8.85418781762039 * 10.0^-12    # Электрическая постоянная [м⁻³ * кг⁻¹ * c⁴ * А²]

    m = M / Nₐ    # Масса одной молекулы газа [кг]
    Tᵣ = T / ε    # Приведенная температура
    δ = μ * 3.33564095 * 10^-30 / sqrt(4 * π * ε₀ * ε * σ₀^3)    # Приведенный дипольный момент
    fₙ = 1 + 3 / 196 * (8 * e_star_ratio(Tᵣ, δ) - 7)^2    # Поправочный коэффициент

    return 5 / 16 * sqrt(m * kB * T / π) * fₙ / (σ₀^2 * collision_integral(Tᵣ, δ))
end

function viscosity(model::PPDS_Vap_Visc, T::Number)    # Динамическая вязкость чистых газов
    A = model.params[1]    # Эмпирические константы уравнения (A, B, C, D, E)
    B = model.params[2]
    C = model.params[3]
    D = model.params[4]
    E = model.params[5]
    return A + B * T + C * T^2 + D * T^3 + E * T^4
end